/** Exp needed to go from `level` to the next level: a gentle curve up to 30, steeper after that. */
export const expForLevel = (level) =>
  Math.round(40 * Math.pow(level, 1.55) * (level <= 30 ? 1 : 1 + Math.pow((level - 30) / 20, 1.5)));

